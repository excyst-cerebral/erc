def table_e6():


    OUT.append(r"% --- auto-generated by report/tables.py (E6: rate budgets) ---")
    OUT.append(r"\begin{tabular}{llccccc}")
    OUT.append(r"\toprule")
    OUT.append(r" & & $m{=}\lceil\bar\eta n\rceil$ & $m_\delta$ & "
               r"Sharp ($m$) & Sharp ($m_\delta$) & Rank shift ($m_\delta$) \\")
    OUT.append(r"\midrule")
    e1 = res["exp1_controlled"]
    for ds, dname in [("mnist", "MNIST"), ("fmnist", "F-MNIST")]:
        for eta in [0.1, 0.2, 0.4]:
            rows = [r for r in e1 if r["dataset"] == ds and r["eta_bar"] == eta
                    and r["n_cal"] == 2000 and r["alpha"] == 0.1]
            m_plug = np.mean([r["m"] for r in rows])
            m_rate = np.mean([r["m_rate"] for r in rows])
            c_ss = row_stats(rows, "sharp_suspect")
            c_sr = row_stats(rows, "sharp_rate")
            c_ur = row_stats(rows, "uniform_shift_rate")
            OUT.append(f"{dname} & " + eta_lbl(eta) + f" & {m_plug:.0f} & "
                       f"{m_rate:.0f} & {fmt(c_ss)} & {fmt(c_sr)} & {fmt(c_ur)} "
                       + r"\\")
    footer()


def table_e7():


    if "milp_equivalence" not in res:
        OUT.append("% E7 pending")
        return
    eq = res["milp_equivalence"]
    sc = res["milp_scaling"]
    OUT.append(r"% --- auto-generated by report/tables.py (E7: robust-CP comparison) ---")
    OUT.append(r"\begin{tabular}{lccccc}")
    OUT.append(r"\toprule")
    OUT.append(r" & & \multicolumn{2}{c}{threshold agreement} & "
               r"\multicolumn{2}{c}{wall time at scale} \\")
    OUT.append(r" & & brute force & MILP & sweep & MILP \\")
    OUT.append(r"\midrule")
    n_bf = eq["trials_bruteforce"] - eq["mismatches_bruteforce"]
    n_mp = eq["trials_milp"] - eq["mismatches_milp"]
    OUT.append(f"agreement on small cases & & {n_bf}/{eq['trials_bruteforce']} & "
               f"{n_mp}/{eq['trials_milp']} & -- & -- " + r"\\")
    for row in sc["rows"]:
        milp_s = row["milp_s"]
        if isinstance(milp_s, float):
            ms = f"{milp_s:.3f} s"
        else:
            ms = str(milp_s)
        OUT.append(f"$n={row['n']}$ & & -- & -- & "
                   f"{row['sweep_s']*1e3:.2f} ms & {ms} " + r"\\")
    OUT.append(r"\bottomrule")
    OUT.append(r"\end{tabular}")


def table_e8():

    if "exp8_annotation_audit" not in res:
        OUT.append("% E8 pending")
        return
    e8 = res["exp8_annotation_audit"]
    OUT.append(r"% --- auto-generated by report/tables.py (E8: annotation audit) ---")
    OUT.append(r"\begin{tabular}{llccccc}")
    OUT.append(r"\toprule")
    OUT.append(r" & & & & \multicolumn{2}{c}{Method} & Clean oracle \\")
    OUT.append(r"method & $\alpha$ & recall & premise & cov. & size & cov. / size \\")
    OUT.append(r"\midrule")
    for name, nname in [("confidence_0.2", "Confidence"),
                        ("audit_1pass", "Audit, 1 pass"),
                        ("audit_2pass", "Audit, 2 passes"),
                        ("audit_pipeline", "Audit pipeline"),
                        ("audited_only_cp", "CP, audited only"),
                        ("random_audit_cp", "CP, random audit"),
                        ("random_audit_fixed_cp", "CP, random audit, fixed $r{=}1000$"),
                        ("oracle_flags", "Oracle $F$ (diag.)")]:
        for alpha in ([0.05, 0.1, 0.2] if name in
                      ("audit_pipeline", "audited_only_cp", "random_audit_cp",
                       "random_audit_fixed_cp")
                      else [0.1, 0.2]):
            rr = [r for r in e8 if r["audit"] == name and r["alpha"] == alpha]
            if not rr:
                continue
            if name in ("audited_only_cp", "random_audit_cp", "random_audit_fixed_cp"):


                OUT.append(
                    f"{nname} & " + alpha_lbl(alpha) +
                    f" & -- & --"
                    f" & {np.mean([r['naive_coverage'] for r in rr]):.3f}"
                    f" & {np.mean([r['naive_size'] for r in rr]):.2f}"
                    f" & {np.mean([r['oracle_clean_coverage'] for r in rr]):.3f} / "
                    f"{np.mean([r['oracle_clean_size'] for r in rr]):.2f} " + r"\\")
                continue
            ph = sum(r["premise_hold"] for r in rr)
            OUT.append(
                f"{nname} & " + alpha_lbl(alpha) +
                f" & {np.mean([r['flag_recall'] for r in rr]):.3f}"
                f" & {ph}/{len(rr)}"
                f" & {np.mean([r['sharp_suspect_coverage'] for r in rr]):.3f}"
                f" & {np.mean([r['sharp_suspect_size'] for r in rr]):.2f}"
                f" & {np.mean([r['oracle_clean_coverage'] for r in rr]):.3f} / "
                f"{np.mean([r['oracle_clean_size'] for r in rr]):.2f} " + r"\\")
    footer()


def emit(name, fn):
    global OUT
    OUT = []
    fn()
    with open(os.path.join(ROOT, name), "w") as f:
        f.write("\n".join(OUT))


