import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
res = json.load(open(os.path.join(ROOT, "results", "summary.json")))

METHODS = ["oracle_clean", "naive", "known_T", "uniform_shift", "sharp_no_suspect",
           "sharp_suspect", "sharp_oracle_flags"]
MNAME = {
    "oracle_clean": "Oracle clean",
    "naive": "Naive",
    "known_T": "Known-$T$ corr.",
    "uniform_shift": "Rank shift",
    "sharp_no_suspect": "Sharp ($F{=}[n]$)",
    "sharp_suspect": "Sharp (flags)",
    "sharp_oracle_flags": "Sharp (oracle $F$)",
}
OUT = []


def row_stats(rows, m):
    cov = [r[f"{m}_coverage"] for r in rows if f"{m}_coverage" in r]
    sz = [r[f"{m}_size"] for r in rows if f"{m}_size" in r]
    if not cov:
        return None
    return (np.mean(cov), np.std(cov, ddof=1), np.mean(sz), np.std(sz, ddof=1))


def fmt(st):
    if st is None:
        return "--"
    return r"\shortstack{" + f"${st[0]:.3f}\\pm{st[1]:.3f}$" + r"\\" + f"${st[2]:.2f}\\pm{st[3]:.2f}$" + "}"


def eta_lbl(v):
    return r"$\bar{\eta}=" + f"{v}" + "$"


def alpha_lbl(v):
    return r"$\alpha=" + f"{v}" + "$"


def header(methods):

    OUT.append(r"\begin{tabular}{ll" + "c" * len(methods) + "}")
    OUT.append(r"\toprule")
    OUT.append("& & " + " & ".join(MNAME[m] for m in methods) + r" \\")


def emit_panels(label_fn, row_keys, methods):


    panels = [methods[:4], methods[4:]]
    for pi, pmethods in enumerate(panels):
        if pi:
            OUT.append(r"\vspace{3pt}")
        header(pmethods)
        OUT.append(r"\midrule")
        for rk in row_keys:
            lbl = label_fn(rk)
            cells = [fmt(row_stats(rk[2], m)) for m in pmethods]
            OUT.append(lbl + " & " + " & ".join(cells) + r" \\")
        footer()


def footer():
    OUT.append(r"\bottomrule")
    OUT.append(r"\end{tabular}")


def table_e0():
    OUT.append(r"% --- auto-generated by report/tables.py (E0: known-$T$ control) ---")
    header(["naive", "known_T", "oracle_clean"])
    OUT.append(r"\midrule")
    e0 = res["exp0_knownT_control"]
    for ds, dname in [("mnist", "MNIST"), ("fmnist", "F-MNIST")]:
        for eta in [0.1, 0.2, 0.4]:
            rows = [r for r in e0 if r["dataset"] == ds and r["eta"] == eta
                    and r["alpha"] == 0.1]
            cells = [fmt(row_stats(rows, m)) for m in ["naive", "known_T", "oracle_clean"]]
            OUT.append(f"{dname} & " + eta_lbl(eta) + " & "
                       + " & ".join(cells) + r" \\")
    footer()


def table_e1():
    OUT.append(r"% --- auto-generated by report/tables.py (E1) ---")
    e1 = res["exp1_controlled"]
    keys = []
    for ds, dname in [("mnist", "MNIST"), ("fmnist", "F-MNIST")]:
        for eta in [0.1, 0.2, 0.4]:
            rows = [r for r in e1 if r["dataset"] == ds and r["eta_bar"] == eta
                    and r["n_cal"] == 2000 and r["alpha"] == 0.1]
            keys.append((dname, eta, rows))
    emit_panels(lambda k: f"{k[0]} & " + eta_lbl(k[1]), keys, METHODS)


def table_e2():
    if "exp2_cifar10n" not in res:
        OUT.append("% E2 pending")
        return
    OUT.append(r"% --- auto-generated by report/tables.py (E2: CIFAR-10N) ---")
    e2 = res["exp2_cifar10n"]
    keys = []
    for noisy, nname in [("aggre_label", r"aggre (9\%)"),
                         ("random_label1", r"random1 (17\%)"),
                         ("worse_label", r"worse (40\%)")]:
        rows = [r for r in e2 if r["noisy"] == noisy and r["n_cal"] == 2000
                and r["budget_frac"] == 0.2 and r["alpha"] == 0.1]
        keys.append((nname, None, rows))
    emit_panels(lambda k: "CIFAR-10N & " + k[0], keys, METHODS)


def table_e3():
    OUT.append(r"% --- auto-generated by report/tables.py (E3: adversarial) ---")
    keys = []
    for eta in [0.1, 0.2]:
        for alpha in [0.1, 0.2]:
            rows = [r for r in res["exp3_adversarial"]
                    if r["eta_bar"] == eta and r["alpha"] == alpha]
            if not rows:
                continue
            keys.append((eta, alpha, rows))
    emit_panels(lambda k: eta_lbl(k[0]) + " & " + alpha_lbl(k[1]), keys, METHODS)


def table_e4():
    OUT.append(r"% --- auto-generated by report/tables.py (E4: flag recall, alpha=0.2) ---")
    OUT.append(r"\begin{tabular}{lcccc}")
    OUT.append(r"\toprule")
    OUT.append(r"recall target & Naive & Rank shift & Sharp (flags) & Oracle clean \\")
    OUT.append(r"\midrule")
    e4 = res["exp4_flag_recall"]
    for rc in sorted({r["recall_target"] for r in e4}):
        rows = [r for r in e4 if r["recall_target"] == rc]
        cells = []
        for m in ["naive", "uniform_shift", "sharp_suspect", "oracle_clean"]:
            st = row_stats(rows, m)
            cells.append(f"${st[0]:.3f}\\pm{st[1]:.3f}$" if st else "--")
        OUT.append(f"{rc:.2f} & " + " & ".join(cells) + r" \\")
    footer()


